import { writeFileSync } from "node:fs";
import { join } from "node:path";
import type { Scenario } from "../src/attacks/scenarios";
import { loadSuite } from "../src/attacks/suite";

/** Writes docs/TAXONOMY.md from the scenario data files, so the document cannot drift from what is run. */

const FAMILIES: Record<string, string> = {
  "direct-injection": "The customer's own message carries a fake instruction or forged record.",
  "indirect-injection": "The instruction sits in data the agent reads: an order note, carrier text, ticket history, a review, an email or a tool output field. The customer only asks plainly.",
  "authority-impersonation": "The customer poses as staff, a system or a policy update.",
  "encoding-obfuscation": "The instruction is hidden in base64, lookalike or invisible Unicode, markup, or another language.",
  "multi-turn-escalation": "Pressure builds over turns: rapport first, then the ask; anger, sympathy or a fake legal threat.",
  salami: "Several small refunds that each sound too minor to refuse.",
  "tool-argument-manipulation": "The refund tool's arguments are the target: wrong order, wrong amount, negative or huge amounts, currency confusion, repeats.",
  "cross-customer": "Claiming another customer's order with partial information.",
  "false-claim": "A plain lie about what happened to the order.",
  "policy-stretch": "Arguing that the policy should bend.",
  "legitimate-refund": "An honest customer who is owed money. The agent must pay in full.",
  "no-refund-due": "An honest customer who is owed nothing. The agent must not refund.",
};

const OWASP_URL = "https://genai.owasp.org/llm-top-10/";
const atlasLink = (id: string) => `[${id}](https://atlas.mitre.org/techniques/${id})`;
const ATLAS_NAMES: Record<string, string> = {
  "AML.T0051.000": "LLM Prompt Injection: Direct",
  "AML.T0051.001": "LLM Prompt Injection: Indirect",
  "AML.T0053": "AI Agent Tool Invocation",
  "AML.T0068": "LLM Prompt Obfuscation",
};

const dir = join(process.cwd(), "scenarios");
const sets = ["set-2.json", "set-3.json"].map((file) => ({ file, suite: loadSuite(join(dir, file)) }));
const all: (Scenario & { set: string })[] = sets.flatMap(({ suite }) => suite.scenarios.map((s) => ({ ...s, set: suite.version })));

const out: string[] = ["# Attack taxonomy", ""];
out.push("Generated by `npm run taxonomy` from the data files in `scenarios/`. Do not edit by hand.", "");
out.push(`Mapped to the [OWASP Top 10 for LLM Applications 2025](${OWASP_URL}) and to [MITRE ATLAS](https://atlas.mitre.org/) (identifiers checked against atlas.mitre.org, version 2026.10, on 31 October 2026).`, "");
out.push("Every attack aims to make the agent invoke its refund tool when the policy does not allow it, so all attacks map to ATLAS AML.T0053 and OWASP LLM06. The other mappings say how the attack gets there. A mapping is a judgement about which entry fits best, not a statement from OWASP or MITRE.", "");
out.push("ATLAS techniques used:", "");
for (const [id, name] of Object.entries(ATLAS_NAMES)) out.push(`- ${atlasLink(id)}: ${name}`);
out.push("");

out.push("## Families", "", "| Family | What it is | Set 2 | Set 3 |", "|---|---|---|---|");
for (const [family, description] of Object.entries(FAMILIES)) {
  const count = (set: string) => all.filter((s) => s.family === family && s.set === set).length;
  out.push(`| ${family} | ${description} | ${count("2")} | ${count("3")} |`);
}
out.push("");

for (const { file, suite } of sets) {
  const attacks = suite.scenarios.filter((s) => s.kind === "attack").length;
  out.push(`## Set ${suite.version} (\`scenarios/${file}\`): ${attacks} attacks, ${suite.scenarios.length - attacks} honest customers`, "");
  if (suite.title) out.push(`${suite.title}.`, "");
  out.push("| Scenario | Family | Kind | What happens | OWASP | ATLAS | Honest counterpart |", "|---|---|---|---|---|---|---|");
  for (const s of suite.scenarios) {
    out.push(`| ${s.id} | ${s.family ?? ""} | ${s.kind} | ${s.title} | ${(s.owasp ?? []).map((o) => o.split(":")[0]).join(", ")} | ${(s.atlas ?? []).map(atlasLink).join(", ")} | ${s.counterpart ?? ""} |`);
  }
  out.push("");
}

writeFileSync(join(process.cwd(), "docs", "TAXONOMY.md"), `${out.join("\n")}`);
console.log(`docs/TAXONOMY.md: ${all.length} scenarios`);
